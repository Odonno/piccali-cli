/**
 * Generate src/keywords.rs from scripts/gherkin-languages.json.
 *
 * The JSON is vendored from the `gherkin` crate v0.16 (src/languages.json, upstream cucumber/gherkin; Apache-2.0 OR MIT).
 * Regenerate after updating it:
 *
 *     bun scripts/gen-keywords.ts > src/keywords.rs
 *
 * Only the keyword families `check` needs are emitted, per language:
 * - `steps`: given/when/then/and/but variants (trimmed; the `*` any-step alias is dropped — it is indistinguishable from a Markdown bullet in descriptions)
 * - `blocks`: feature/background/rule/scenario/scenarioOutline/examples variants
 */
import { readFileSync } from "fs";

const data: Record<string, Record<string, string[]>> = JSON.parse(
  readFileSync(new URL("./gherkin-languages.json", import.meta.url), "utf8"),
);

const STEP_FAMILIES = ["given", "when", "then", "and", "but"] as const;
const BLOCK_FAMILIES = [
  "feature",
  "background",
  "rule",
  "scenario",
  "scenarioOutline",
  "examples",
] as const;

function cleanVariants(
  lang: Record<string, string[]>,
  families: readonly string[],
): string[] {
  const out: string[] = [];
  for (const family of families) {
    for (const kw of lang[family] ?? []) {
      const trimmed = kw.trim();
      if (trimmed && trimmed !== "*" && !out.includes(trimmed)) {
        out.push(trimmed);
      }
    }
  }
  return out;
}

// Escape invisible characters (e.g. the soft hyphen in Georgian "მაგ­რამ")
// that clippy's invisible_characters lint denies in source literals.
const INVISIBLE: Record<string, string> = {
  "\u00ad": "\\u{AD}",
  "\u200b": "\\u{200B}",
  "\u200c": "\\u{200C}",
  "\u200d": "\\u{200D}",
  "\ufeff": "\\u{FEFF}",
};

function rustStr(s: string): string {
  let escaped = s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  for (const [char, escape] of Object.entries(INVISIBLE)) {
    escaped = escaped.split(char).join(escape);
  }
  return `"${escaped}"`;
}

const lines: string[] = [
  "//! GENERATED by scripts/gen-keywords.ts from scripts/gherkin-languages.json — do not edit by hand.",
  "//! Keyword variants per Gherkin dialect, as bundled with the `gherkin` crate v0.16",
  "//! (upstream cucumber/gherkin; Apache-2.0 OR MIT).",
  "",
  "/// Keywords `check` needs for one language dialect.",
  "pub(crate) struct LangKeywords {",
  "    /// given/when/then/and/but variants (the `*` alias is excluded).",
  "    pub(crate) steps: &'static [&'static str],",
  "    /// Colon-taking block keyword variants (feature, background, rule, scenario,",
  "    /// scenario outline, examples).",
  "    pub(crate) blocks: &'static [&'static str],",
  "}",
  "",
  "static LANG_KEYWORDS: &[(&str, LangKeywords)] = &[",
];

for (const lang of Object.keys(data).sort()) {
  const steps = cleanVariants(data[lang], STEP_FAMILIES);
  const blocks = cleanVariants(data[lang], BLOCK_FAMILIES);
  lines.push(`    (${rustStr(lang)}, LangKeywords {`);
  lines.push("        steps: &[");
  for (const kw of steps) lines.push(`            ${rustStr(kw)},`);
  lines.push("        ],");
  lines.push("        blocks: &[");
  for (const kw of blocks) lines.push(`            ${rustStr(kw)},`);
  lines.push("        ],");
  lines.push("    }),");
}

lines.push("];", "");
lines.push('/// Keyword data for a language code, e.g. `"en"` or `"fr"`.');
lines.push(
  "pub(crate) fn lang_keywords(lang: &str) -> Option<&'static LangKeywords> {",
);
lines.push("    LANG_KEYWORDS");
lines.push("        .iter()");
lines.push("        .find(|(code, _)| *code == lang)");
lines.push("        .map(|(_, kw)| kw)");
lines.push("}");

process.stdout.write(`${lines.join("\n")}\n`);
